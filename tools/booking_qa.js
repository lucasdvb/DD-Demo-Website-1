// Drives the booking pop-up: open from a Reserve card, pick a day + time, submit.
// usage: node tools/booking_qa.js <outDir> <url>
const fs = require('fs')
const { chromium } = require(process.env.PW_PATH || '/opt/node-tools/node_modules/playwright')
;(async () => {
  const [out, url] = process.argv.slice(2)
  fs.mkdirSync(out, { recursive: true })
  const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox'] })
  const logs = []
  for (const [name, vp, mobile] of [['desk', { width: 1440, height: 900 }, false], ['mob', { width: 390, height: 844 }, true]]) {
    const page = await (await browser.newContext({ viewport: vp, isMobile: mobile, hasTouch: mobile })).newPage()
    page.on('pageerror', e => logs.push(`[${name}] pageerror ${e.message}`))
    await page.goto(url, { waitUntil: 'networkidle' })
    await page.waitForTimeout(3500)
    await page.screenshot({ path: `${out}/${name}-hero.png` })
    const reserve = page.locator('.mr-exp__card').nth(3).locator('a[href="#book"]')
    await reserve.scrollIntoViewIfNeeded()
    await page.waitForTimeout(600)
    await reserve.click({ force: true })
    await page.waitForTimeout(1300)
    await page.screenshot({ path: `${out}/${name}-modal-open.png` })
    const days = page.locator('.mr-day:not([disabled])')
    await days.nth(3).click()
    await page.waitForTimeout(500)
    await page.locator('.mr-slot:not([disabled])').nth(1).click()
    await page.fill('#mr-b-name', 'Test Guest')
    await page.fill('#mr-b-email', 'guest@example.com')
    await page.locator('[data-guests="1"]').click()
    await page.waitForTimeout(400)
    await page.screenshot({ path: `${out}/${name}-modal-filled.png` })
    await page.locator('.mr-book__submit').scrollIntoViewIfNeeded()
    await page.locator('.mr-book__submit').click()
    await page.waitForTimeout(1800)
    await page.screenshot({ path: `${out}/${name}-modal-done.png` })
    logs.push(`[${name}] ritual=${await page.inputValue('#mr-b-ritual')} done=${await page.isVisible('.mr-book__view--done')} text="${await page.textContent('.mr-done__text')}"`)
    await page.keyboard.press('Escape')
    await page.waitForTimeout(900)
    logs.push(`[${name}] closed=${!(await page.evaluate(() => document.querySelector('.mr-book').classList.contains('is-open')))} radius=${await page.evaluate(() => getComputedStyle(document.querySelector('.mr-btn--solid')).borderRadius)}`)
  }
  await browser.close()
  console.log(logs.join('\n'))
})()
